import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { performance } from "node:perf_hooks";
import { parseRubric } from "../lib/rubric.ts";

let parserChecks = 0;
const valid = (text) => { parserChecks += 1; return parseRubric(text); };
const invalid = (text, pattern) => {
  parserChecks += 1;
  assert.throws(() => parseRubric(text), pattern);
};
const example = "Presentation | 40 marks\n  Content | 2\n  Delivery | 1\n\nReport | 60 marks\n  Analysis | 1";
const rubric = valid(example);
assert.equal(rubric.totalMarks, 100);
assert.equal(rubric.itemCount, 3);
assert.equal(rubric.components[0].items[0].weight, 2);
assert.equal(valid("\uFEFFPart | 2.5 marks\r\n\tItem | .5\r\n").totalMarks, 2.5);
assert.equal(valid("=SUM(A1) & <test> | 1 mark\n  +Literal | 1").components[0].name, "=SUM(A1) & <test>");
invalid("", /Enter a rubric/);
invalid("Part | 1 marks", /Line 1: Add at least one/);
invalid("  Item | 1", /Line 1: Add a component/);
invalid("Part | 1\n  Item | 1", /Line 1: End a component/);
invalid("Part | 0 marks\n  Item | 1", /Line 1: Use a positive decimal/);
invalid("Part | -1 marks\n  Item | 1", /Line 1: Use a positive decimal/);
invalid("Part | 1 marks\n  Item | 1e2", /Line 2: Use a positive decimal/);
invalid("Part | 1 marks\n  Item | 0", /Line 2: Use a positive decimal/);
invalid("Part | 1 marks\n  Item | NaN", /Line 2: Use a positive decimal/);
invalid("Part | 1 marks\n  Item | Infinity", /Line 2: Use a positive decimal/);
invalid("Part | 1000001 marks\n  Item | 1", /Line 1: Use a mark value from/);
invalid("Part | 1 marks\n  Item | 0.0000001", /Line 2: Use a weight from/);
invalid("Part | 1 marks\n  Item | 1.0000001", /Line 2: Use a weight from/);
assert.equal(valid("Part | 0.000001 marks\n  Item | 1000000").totalMarks, .000001);
invalid("Part | 1 marks\n    Nested | 1", /Line 2: Indent subitems/);
invalid("Part | 1 marks\n Item | 1", /Line 2: Indent subitems/);
invalid("Part | 1 marks\n  Item | 1\n\tMixed | 1", /Line 3: Use the same indentation/);
invalid("Part | 1 marks\n  Item | 1\nEmpty | 1 marks\nNext | 1 marks\n  Item | 1", /Line 3: Add at least one/);
invalid("Part | 1 marks\n  Item | 1 | 2", /Line 2: Use/);
invalid("Part | 1 marks\n  | 2", /Line 2: Add a name/);
invalid("P".repeat(181) + " | 1 marks\n  Item | 1", /Line 1: Shorten the name/);
invalid("Part | 1 marks\n  Bad\u0001 | 1", /Line 2: Remove the unsupported/);
invalid("Part | 1 marks\n  Bad\tname | 1", /Line 2: Remove extra/);
invalid("x".repeat(30_001), /too long/);
invalid(Array.from({ length: 31 }, (_, i) => `Part ${i} | 1 marks\n  Item | 1`).join("\n"), /Line 61: Use at most 30/);
invalid("Part | 1 marks\n" + Array.from({ length: 201 }, (_, i) => `  Item ${i} | 1`).join("\n"), /Line 202: Use at most 200/);
console.log(`Parser: ${parserChecks} cases passed.`);

const { createWorkbook } = await import("../lib/workbook.ts");
const output = new URL("./output/", import.meta.url);
await fs.mkdir(output, { recursive: true });
await fs.writeFile(new URL("grading.xlsx", output), await createWorkbook(rubric));
await fs.writeFile(new URL("literal-labels.xlsx", output), await createWorkbook(parseRubric("=SUM(A1) & <test> | 1 marks\n  +Literal | 1")));
const largeText = Array.from({ length: 30 }, (_, i) => `Component ${i + 1} | 1 marks\n` + Array.from({ length: i < 20 ? 7 : 6 }, (_, j) => `  Subitem ${j + 1} | 1`).join("\n")).join("\n");
const large = parseRubric(largeText);
assert.equal(large.itemCount, 200);
const start = performance.now();
const bytes = await createWorkbook(large);
await fs.writeFile(new URL("capacity.xlsx", output), bytes);
console.log(`Generator: 30 components, 200 subitems, 100 student columns; ${bytes.byteLength} bytes in ${Math.round(performance.now() - start)} ms.`);
